$("#contact").on("keyup", function () {
    let valor = $(this).val();
    let phoneRegex = /^[0-9]{10,11}$/;
    
    if (phoneRegex.test(valor)) {
        $("#scontact").text("");
        return 1;
    } else {
        $("#scontact").text("Enter a valid phone number");
        return 0;
    }
});

